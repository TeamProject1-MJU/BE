-- ERD v1.13 subway graph and congestion; stations already exists (V4).
create table subway_lines (
    id bigint generated by default as identity primary key,
    line_code varchar(10) not null,
    name varchar(20) not null,
    color char(7) not null,
    sort_order int not null,
    constraint uq_lines_code unique (line_code),
    constraint ck_lines_color check (color ~ '^#[0-9A-Fa-f]{6}$')
);

-- Graph node = (station, line).
create table station_lines (
    id bigint generated by default as identity primary key,
    station_id bigint not null,
    line_id bigint not null,
    station_code varchar(10) not null,
    seq int not null,
    branch_code varchar(20) not null default 'MAIN',
    constraint uq_sl_station_line unique (station_id, line_id),
    constraint uq_sl_line_code unique (line_id, station_code),
    constraint uq_sl_line_branch_seq unique (line_id, branch_code, seq),
    constraint ck_sl_seq check (seq >= 1),
    constraint fk_sl_station foreign key (station_id) references stations (id),
    constraint fk_sl_line foreign key (line_id) references subway_lines (id)
);

create table station_connections (
    id bigint generated by default as identity primary key,
    from_station_line_id bigint not null,
    to_station_line_id bigint not null,
    connection_type varchar(8) not null,
    direction varchar(5),
    travel_seconds int not null,
    distance_m int not null,
    constraint uq_conn_from_to unique (from_station_line_id, to_station_line_id),
    constraint ck_conn_not_self check (from_station_line_id <> to_station_line_id),
    constraint ck_conn_dir check (
        (connection_type = 'RIDE' and direction is not null)
        or (connection_type = 'TRANSFER' and direction is null)
    ),
    constraint ck_conn_nonneg check (travel_seconds > 0 and distance_m >= 0),
    constraint ck_conn_type check (connection_type in ('RIDE', 'TRANSFER')),
    constraint ck_conn_direction_val check (direction is null or direction in ('UP', 'DOWN', 'INNER', 'OUTER', 'LOOP')),
    constraint fk_conn_from foreign key (from_station_line_id) references station_lines (id),
    constraint fk_conn_to foreign key (to_station_line_id) references station_lines (id)
);

create index idx_conn_to on station_connections (to_station_line_id);

create table congestion_stats (
    id bigint generated by default as identity primary key,
    station_line_id bigint not null,
    direction varchar(5) not null,
    day_type varchar(8) not null,
    slot_start time not null,
    congestion_pct numeric(5, 1) not null,
    congestion_level varchar(12) not null,
    congestion_level_label varchar(10) not null,
    source varchar(9) not null,
    model_version varchar(20),
    constraint uq_cong_slot_source unique (station_line_id, direction, day_type, slot_start, source),
    constraint ck_cong_pct check (congestion_pct >= 0),
    constraint ck_cong_slot check (
        extract(minute from slot_start) in (0, 30) and slot_start between time '06:00' and time '23:00'
    ),
    constraint ck_cong_model check ((source = 'PREDICTED') = (model_version is not null)),
    -- Lower bound inclusive, upper bound exclusive. The label is stored as loaded, without a CHECK.
    constraint ck_cong_level check (
        congestion_level in ('COMFORTABLE', 'RELAXED', 'NORMAL', 'CROWDED', 'VERY_CROWDED')
        and (
            (congestion_level = 'COMFORTABLE' and congestion_pct < 35)
            or (congestion_level = 'RELAXED' and congestion_pct >= 35 and congestion_pct < 50)
            or (congestion_level = 'NORMAL' and congestion_pct >= 50 and congestion_pct < 100)
            or (congestion_level = 'CROWDED' and congestion_pct >= 100 and congestion_pct < 150)
            or (congestion_level = 'VERY_CROWDED' and congestion_pct >= 150)
        )
    ),
    constraint ck_cong_direction check (direction in ('UP', 'DOWN', 'INNER', 'OUTER', 'LOOP')),
    constraint ck_cong_day check (day_type in ('WEEKDAY', 'SATURDAY', 'SUNDAY')),
    -- Seoul Metro measurements (ACTUAL) are not loaded.
    constraint ck_cong_source check (source in ('PREDICTED', 'MOCK')),
    constraint fk_cong_station_line foreign key (station_line_id) references station_lines (id)
);
